#!/usr/bin/env python3
"""Regenerate tests/fixtures/json_conformance/manifest.txt from cases/.

The manifest is the asserted denominator for tests/json/conformance.rock: the
harness reads it rather than listing a directory, so a case file that vanishes
is a failure instead of a silently smaller run.

Expectation comes from the JSONTestSuite prefix and nothing else. Cases where
this parser disagrees with the expectation are pinned in the harness's own
divergence table, not here -- generated and hand-authored evidence stay apart.

Usage: python3 scripts/gen_json_conformance_manifest.py
"""

import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..",
                    "tests", "fixtures", "json_conformance")
EXPECT = {"y": "accept", "n": "reject", "i": "either"}


def main():
    cases_dir = os.path.join(ROOT, "cases")
    names = sorted(n for n in os.listdir(cases_dir) if n.endswith(".json"))
    if not names:
        sys.exit("no cases found in %s" % cases_dir)

    lines = [
        "# Generated by scripts/gen_json_conformance_manifest.py -- do not hand-edit.",
        "# <expect>\t<case file>   expect: accept | reject | either",
    ]
    counts = {"accept": 0, "reject": 0, "either": 0}
    for name in names:
        prefix = name[0]
        if prefix not in EXPECT:
            sys.exit("unexpected case prefix: %s" % name)
        expect = EXPECT[prefix]
        counts[expect] += 1
        lines.append("%s\t%s" % (expect, name))

    with open(os.path.join(ROOT, "manifest.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")

    print("%d cases: %d accept, %d reject, %d either"
          % (len(names), counts["accept"], counts["reject"], counts["either"]))


if __name__ == "__main__":
    main()
