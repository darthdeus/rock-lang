pub fn stone_event_layout(header: &str) -> Result<String, String> {
    let (before, _) = header
        .split_once("} StoneEvent;")
        .ok_or("missing StoneEvent typedef")?;
    let (_, body) = before
        .rsplit_once("typedef struct {")
        .ok_or("missing StoneEvent fields")?;
    let mut rust =
        String::from("#[repr(C)]\n#[derive(Debug, Clone, Copy)]\npub struct StoneEvent {\n");
    let mut text_len = None;
    for field in body
        .split(';')
        .map(str::trim)
        .filter(|field| !field.is_empty())
    {
        let (c, name) = field
            .rsplit_once(' ')
            .ok_or_else(|| format!("invalid StoneEvent field: {field}"))?;
        let c = c.trim();
        let (name, ty) = match (c, name) {
            ("StoneEventType", "type") => ("event_type", "crate::StoneEventType"),
            ("StoneKeyCode", "key") | ("int", _) => (name, "::std::ffi::c_int"),
            ("bool", _) => (name, "bool"),
            ("const char*", _) => (name, "*const ::std::ffi::c_char"),
            ("char", _) if name.starts_with("text[") && name.ends_with(']') => {
                text_len = Some(
                    name[5..name.len() - 1]
                        .parse::<usize>()
                        .map_err(|e| e.to_string())?,
                );
                ("text", "[::std::ffi::c_char; STONE_TEXT_INPUT_BYTES]")
            }
            _ => return Err(format!("unsupported StoneEvent field: {field}")),
        };
        writeln!(rust, "    pub {name}: {ty},").unwrap();
    }
    rust.push_str("}\n");
    let text_len = text_len
        .filter(|len| *len > 0)
        .ok_or("missing StoneEvent text extent")?;
    writeln!(
        rust,
        "pub(crate) const STONE_TEXT_INPUT_BYTES: usize = {text_len};"
    )
    .unwrap();
    Ok(rust)
}
