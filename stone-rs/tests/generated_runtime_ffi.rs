const GENERATED: &str = "// Generated by stone-rs/build.rs.\n";

#[test]
fn runtime_typed_bindings_are_generated() {
    let rock = include_str!("../../packages/stone/engine/runtime_ffi.rock");
    let (_, generated) = rock.split_once(GENERATED).unwrap();
    assert_eq!(generated.matches("extern(ffi,").count(), 184);
}

#[test]
fn teardown_keeps_its_c_symbol_for_the_rock_lifecycle_wrapper() {
    let header = include_str!("../../packages/stone/engine/runtime_ffi.h");
    let (authored, generated) = header.split_once(GENERATED).unwrap();
    assert!(authored.contains("uint8_t stone_teardown(void);"));
    assert!(!generated.contains("stone_teardown("));
}

#[test]
fn event_poll_uses_the_c_owned_layout() {
    let header = include_str!("../../packages/stone/engine/runtime_ffi.h");
    let (layout, declarations) = header.split_once(GENERATED).unwrap();
    assert!(layout.contains("} StoneEvent;"));
    assert!(declarations.contains("uint8_t stone_poll_event(StoneEvent* event);"));

    let rock = include_str!("../../packages/stone/engine/runtime_ffi.rock");
    let (_, generated) = rock.split_once(GENERATED).unwrap();
    assert!(generated.lines().any(
        |line| line == "extern(ffi, \"stone\") fn stone_poll_event(event: StoneEvent) -> bool"
    ));
}
