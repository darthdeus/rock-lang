const GENERATED: &str = "// Generated by stone-rs/build.rs.\n";

#[test]
fn runtime_typed_bindings_are_generated() {
    let rock = include_str!("../../packages/stone/engine/runtime_ffi.rock");
    let (_, generated) = rock.split_once(GENERATED).unwrap();
    assert_eq!(generated.matches("extern(ffi,").count(), 164);
}
