const BINDINGS: &str = include_str!("../../packages/stone/engine/rendering_ffi.rock");
const HEADER: &str = include_str!("../../packages/stone/engine/rendering_ffi.h");
const GENERATED: &str = "// Generated by stone-rs/build.rs.\n";

#[test]
fn rendering_bindings_are_generated_once() {
    let (authored, generated) = BINDINGS.split_once(GENERATED).unwrap();
    let (authored_c, generated_c) = HEADER.split_once(GENERATED).unwrap();
    let names: Vec<_> = generated
        .lines()
        .filter_map(|line| {
            let (_, declaration) = line.split_once("extern(ffi, \"stone\") fn ")?;
            Some(declaration.split_once('(').unwrap().0)
        })
        .collect();

    assert_eq!(names.len(), 190);
    assert!(!authored.contains("extern(ffi, \"stone\")"));
    for name in names {
        assert!(!authored.contains(&format!("fn {name}(")), "{name}");
        assert!(!authored_c.contains(&format!(" {name}(")), "{name}");
        assert_eq!(
            generated_c.matches(&format!(" {name}(")).count(),
            1,
            "{name}"
        );
    }
}

#[test]
fn header_declares_the_native_renderer_table_in_rust_field_order() {
    let (_, body) = HEADER
        .split_once("typedef struct StoneNativeRendererApiV1 {")
        .expect("rendering_ffi.h declares StoneNativeRendererApiV1");
    let (body, _) = body.split_once("} StoneNativeRendererApiV1;").unwrap();
    let fields: Vec<&str> = body
        .lines()
        .map(str::trim)
        .filter(|line| line.ends_with(';'))
        .map(|line| match line.split_once("(*") {
            Some((_, rest)) => rest.split_once(')').unwrap().0,
            None => line.trim_end_matches(';').rsplit(' ').next().unwrap(),
        })
        .collect();
    assert_eq!(
        fields,
        stone_rs::native_renderer::STONE_NATIVE_RENDERER_API_V1_FIELDS
    );
}
